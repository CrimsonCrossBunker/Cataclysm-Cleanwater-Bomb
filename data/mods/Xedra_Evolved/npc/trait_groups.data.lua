-- Picks one of the main reasons to be a vampire and applies them to this NPC.  This determines how the dialogue goes.
-- Unwilling: Anyone who became a vampire against their will.  Very open to the cure.
-- Power-Hungry: Those who want the powers granted by this condition.  Will always refuse the cure.
-- Vengeful: Unwilling who were almost killed and decided that their best bet is to become a stronger vampire.  The name is because most pre-cataclysm Vengefuls are caused by vampire hunters.
-- Deluded: "Vampires are cool.  I wanna be one".  Hard but possible to persuade to take the cure.
-- Due to the end of the world vampires made this recently have other reasons than being cured of something, thus the Seekers aren't included here.  They would also be part of the impossible-to-persuade as even panacea wouldn't be enough to treat their afflictions.
-- The other reasons are far less common, so they're not included here.
ccb.content.define_trait_group {
    id = "Random_vampire_reason",
    kind = "distribution",
    entries = {
        { trait = "VAMPIRE_REASON_UNWILLING", weight = 10 },
        { trait = "VAMPIRE_REASON_POWER_HUNGRY", weight = 10 },
        { trait = "VAMPIRE_REASON_VENGEFUL", weight = 10 },
        { trait = "VAMPIRE_REASON_DELUDED", weight = 10 },
    },
}
