local ccb = require("ccb")
local content = ccb.content
local spell_message = ccb.content.text("You cast %s!")
local spell_sound = ccb.content.text("an explosion.")
local calorie_cost = { id = "mom_aea_artifact_calorie_hit", self = true }

local function add_spell(options)
    local impact = options.impact
    options.impact = nil
    options.message = options.message or spell_message
    options.sound_description = spell_sound
    local spell = content.Spell(options)
    if impact then
        spell:lua_impact(impact)
    end
    content.add(spell)
end

